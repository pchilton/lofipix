import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { getIconData, iconToSVG } from '@iconify/utils';
import type { IconifyJSON } from '@iconify/types';

const collections = {
  lucide: [
    'camera',
    'check',
    'chevron-left',
    'chevron-right',
    'cloud',
    'image',
    'log-out',
    'refresh-cw',
    'trash-2',
    'plus',
    'x',
    'alert-circle',
    'wifi-off',
    'upload',
    'folder-open',
    'rotate-ccw',
  ],
  mdi: ['car-wrench'],
} as const;

type IconRecord = { body: string; width: number; height: number };

const output: Record<string, IconRecord> = {};

for (const [prefix, names] of Object.entries(collections)) {
  const file = join(
    process.cwd(),
    'node_modules',
    '@iconify-json',
    prefix,
    'icons.json',
  );
  const iconSet = JSON.parse(readFileSync(file, 'utf8')) as IconifyJSON;

  for (const name of names) {
    const data = getIconData(iconSet, name);
    if (!data) {
      throw new Error(`Icon ${prefix}:${name} was not found.`);
    }
    const rendered = iconToSVG(data, { height: '1em' });
    output[`${prefix}:${name}`] = {
      body: rendered.body,
      width: data.width ?? 24,
      height: data.height ?? 24,
    };
  }
}

const source = `// Generated by npm run icons:generate. Do not edit by hand.

export interface IconRecord {
  body: string;
  width: number;
  height: number;
}

export const icons = ${JSON.stringify(output, null, 2)} as const;

export type IconName = keyof typeof icons;

export const iconNames = Object.keys(icons) as IconName[];
`;

writeFileSync(join(process.cwd(), 'src', 'icons', 'registry.ts'), source);
console.log(`Wrote ${Object.keys(output).length} icons.`);
