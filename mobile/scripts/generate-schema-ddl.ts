import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { getTableConfig, type SQLiteColumn } from 'drizzle-orm/sqlite-core';

import {
  albums,
  localMeta,
  outbox,
  photoLocations,
  photos,
  storageProviders,
} from '../src/lib/db/schema';

const tables = [albums, photos, photoLocations, storageProviders, outbox, localMeta];

function sqlType(column: SQLiteColumn): string {
  if (column.columnType === 'SQLiteReal') {
    return 'real';
  }
  if (column.columnType === 'SQLiteInteger' || column.columnType === 'SQLiteBoolean' || column.columnType === 'SQLiteTimestamp') {
    return 'integer';
  }
  return 'text';
}

function defaultSql(column: SQLiteColumn): string | null {
  if (!column.hasDefault || column.default === undefined) {
    return null;
  }
  const value = column.default;
  if (typeof value === 'boolean') {
    return value ? '1' : '0';
  }
  if (typeof value === 'number') {
    return String(value);
  }
  if (typeof value === 'string') {
    return `'${value.replaceAll("'", "''")}'`;
  }
  return null;
}

function columnSql(column: SQLiteColumn): string {
  const parts = [column.name, sqlType(column)];
  if (column.primary) parts.push('primary key');
  if (column.notNull && !column.primary) parts.push('not null');
  const fallback = defaultSql(column);
  if (fallback) parts.push(`default ${fallback}`);
  return `    ${parts.join(' ')}`;
}

function tableSql(table: (typeof tables)[number]): string[] {
  const config = getTableConfig(table);
  const statements = [
    `  \`create table if not exists ${config.name} (\n${config.columns.map(columnSql).join(',\n')}\n  )\`,`,
  ];

  for (const index of config.indexes) {
    const columns = index.config.columns
      .map((column) => (column as SQLiteColumn).name)
      .join(', ');
    statements.push(
      `  \`create index if not exists ${index.config.name} on ${config.name} (${columns})\`,`,
    );
  }

  return statements;
}

const statements = tables.flatMap(tableSql);
const source = `// Generated by bun run schema:generate from src/lib/db/schema.ts. Do not edit by hand.\n\nexport const schemaStatements = [\n${statements.join('\n')}\n] as const;\n`;

writeFileSync(join(process.cwd(), 'src', 'lib', 'db', 'ddl.ts'), source);
console.log(`Wrote DDL for ${tables.length} tables.`);
